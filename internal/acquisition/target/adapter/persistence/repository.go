// Package persistence implements the PostgreSQL adapter for acquisition
// targets. It owns target SQL and database/transaction lifecycle; callers cross
// the boundary with typed values and an opaque txscope.Tx only.
package persistence

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"time"

	targetdomain "bansoko/internal/acquisition/target"
	generated "bansoko/internal/acquisition/target/adapter/persistence/generated"
	"bansoko/internal/persistence/txscope"
)

// Repository owns PostgreSQL access for frozen acquisition targets and their
// latest observations. Transactional writes use a caller-owned scope. The
// adapter owns the transaction lifecycle only for the complete explicit scan
// operation.
type Repository struct {
	db *sql.DB
}

// NewRepository wires the PostgreSQL target adapter.
func NewRepository(db *sql.DB) *Repository {
	return &Repository{db: db}
}

func (r *Repository) requireDB(operation string) error {
	if r == nil || r.db == nil {
		return fmt.Errorf("%s database is nil", operation)
	}
	return nil
}

type targetSpec struct {
	ID                string
	TargetRef         string
	SourcePath        string
	MediaKind         string
	TargetPath        string
	ExpectedSizeBytes int64
	Intent            string
	CollisionPolicy   string
	RenderSnapshot    json.RawMessage
	ConfigSnapshot    json.RawMessage
	SpecDigest        string
}

type targetSet struct {
	ReleaseID string
	Targets   []targetSpec
}

type observationRow struct {
	TargetID          string
	State             string
	ObservedSizeBytes *int64
	ReasonCode        string
	ObservedAt        time.Time
}

// ReadTargets returns frozen target facts for one managed-anime instance. The
// bool is false when the instance is missing/deleted.
//
// The read also fences the lifecycle: a retired instance preserves its owner
// graph but admits no observation write, so the explicit scan stops here with
// the typed 409 retirement boundary before probing or persisting anything. An
// instance without a lifecycle row (synthetic/legacy id) keeps the previous
// behavior.
func (r *Repository) ReadTargets(ctx context.Context, managedAnimeID string) ([]targetdomain.TargetRow, bool, error) {
	if err := r.requireDB("target scan"); err != nil {
		return nil, false, err
	}
	var lifecycleState string
	err := r.db.QueryRowContext(ctx, `
SELECT lifecycle_state FROM managed_anime WHERE id = $1`, managedAnimeID).Scan(&lifecycleState)
	switch {
	case errors.Is(err, sql.ErrNoRows):
	case err != nil:
		return nil, false, fmt.Errorf("read target scan lifecycle: %w", err)
	case lifecycleState != "active":
		return nil, false, targetdomain.ErrInstanceRetired
	}
	queries := generated.New(r.db)
	rows, err := queries.ReadTargets(ctx, managedAnimeID)
	if err != nil {
		return nil, false, fmt.Errorf("read targets: %w", err)
	}
	targets := make([]targetdomain.TargetRow, 0, len(rows))
	for _, row := range rows {
		targets = append(targets, targetdomain.TargetRow{
			ID:                row.ID,
			TargetPath:        row.TargetPath,
			ExpectedSizeBytes: row.ExpectedSizeBytes,
		})
	}
	if len(targets) > 0 {
		return targets, true, nil
	}

	exists, err := queries.ManagedAnimeExists(ctx, managedAnimeID)
	if err != nil {
		return nil, false, fmt.Errorf("verify instance: %w", err)
	}
	return targets, exists, nil
}

// PersistObservations maps application observations and owns the transaction
// for the complete explicit scan operation.
func (r *Repository) PersistObservations(ctx context.Context, observations []targetdomain.Observation) error {
	if err := r.requireDB("target scan"); err != nil {
		return err
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin observation transaction: %w", err)
	}
	defer tx.Rollback()
	for _, observation := range mapObservations(observations) {
		if err := upsertObservation(ctx, txscope.Wrap(tx), observation); err != nil {
			return err
		}
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit observations: %w", err)
	}
	return nil
}

// ReadObservationVersions returns the durable versions generated by an
// observation upsert. The query is bounded by the scanner's target set. The
// target IDs are supplied as one bound PostgreSQL array by the caller's driver.
func (r *Repository) ReadObservationVersions(ctx context.Context, targetIDs []string) (map[string]int64, error) {
	if err := r.requireDB("target scan"); err != nil {
		return nil, err
	}
	versions := make(map[string]int64, len(targetIDs))
	if len(targetIDs) == 0 {
		return versions, nil
	}
	rows, err := generated.New(r.db).ReadObservationVersions(ctx, targetIDs)
	if err != nil {
		return nil, fmt.Errorf("read observation versions: %w", err)
	}
	for _, row := range rows {
		versions[row.TargetID] = row.Version
	}
	for _, id := range targetIDs {
		if _, ok := versions[id]; !ok {
			return nil, fmt.Errorf("target %s: %w", id, sql.ErrNoRows)
		}
	}
	return versions, nil
}

// ReplaceSet persists a frozen target set in the caller-owned transaction. It
// never begins, commits, or rolls back that transaction.
func (r *Repository) ReplaceSet(ctx context.Context, scope txscope.Tx, set targetdomain.Set) error {
	return replaceSet(ctx, scope, mapTargetSet(set))
}

func replaceSet(ctx context.Context, scope txscope.Tx, set targetSet) error {
	tx, err := transaction(scope)
	if err != nil {
		return err
	}
	if set.ReleaseID == "" || len(set.Targets) == 0 {
		return errors.New("target store: at least one target is required")
	}

	queries := generated.New(tx)
	targetRefs := make([]string, 0, len(set.Targets))
	for _, spec := range set.Targets {
		targetRefs = append(targetRefs, spec.TargetRef)
	}
	if _, err := queries.DeleteStaleTargets(ctx, generated.DeleteStaleTargetsParams{
		ReleaseID:  set.ReleaseID,
		TargetRefs: targetRefs,
	}); err != nil {
		return fmt.Errorf("remove stale acquisition targets: %w", err)
	}
	for _, spec := range set.Targets {
		if err := queries.UpsertTarget(ctx, generated.UpsertTargetParams{
			ID:                spec.ID,
			ReleaseID:         set.ReleaseID,
			TargetRef:         spec.TargetRef,
			SourcePath:        spec.SourcePath,
			MediaKind:         spec.MediaKind,
			TargetPath:        spec.TargetPath,
			ExpectedSizeBytes: spec.ExpectedSizeBytes,
			Intent:            spec.Intent,
			CollisionPolicy:   spec.CollisionPolicy,
			RenderSnapshot:    normalizeObject(spec.RenderSnapshot),
			ConfigSnapshot:    normalizeObject(spec.ConfigSnapshot),
			SpecDigest:        spec.SpecDigest,
		}); err != nil {
			return fmt.Errorf("persist target %s: %w", spec.TargetRef, err)
		}
	}
	return nil
}

// UpsertObservation persists one latest observation in the caller-owned
// transaction. It never begins, commits, or rolls back that transaction.
func (r *Repository) UpsertObservation(ctx context.Context, scope txscope.Tx, observation targetdomain.Observation) error {
	return upsertObservation(ctx, scope, mapObservation(observation))
}

func upsertObservation(ctx context.Context, scope txscope.Tx, observation observationRow) error {
	tx, err := transaction(scope)
	if err != nil {
		return err
	}
	if observation.TargetID == "" {
		return errors.New("target store: target id is required")
	}
	var releaseID string
	if err := tx.QueryRowContext(ctx, `SELECT release_id FROM acquisition_targets WHERE id=$1`, observation.TargetID).Scan(&releaseID); err != nil {
		return err
	}
	// Artifact rows of the release are locked (in id order) before the target
	// observation, the same order the artifact writers use.
	rows, err := tx.QueryContext(ctx, `SELECT a.id FROM artifacts a JOIN download_tasks dt ON dt.id=a.download_task_id WHERE dt.release_id=$1 ORDER BY a.id FOR UPDATE OF a`, releaseID)
	if err != nil {
		return err
	}
	for rows.Next() { // locking only
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	var lockedRelease string
	if err := tx.QueryRowContext(ctx, `SELECT public.target_lock_observation($1)`, observation.TargetID).Scan(&lockedRelease); err != nil {
		return err
	}
	if lockedRelease != releaseID {
		return errors.New("target release changed during observation admission")
	}
	if observation.ObservedAt.IsZero() {
		observation.ObservedAt = time.Now().UTC()
	}
	if err := generated.New(tx).UpsertObservation(ctx, generated.UpsertObservationParams{
		TargetID:          observation.TargetID,
		State:             observation.State,
		ObservedSizeBytes: nullableInt64(observation.ObservedSizeBytes),
		ReasonCode:        nullableString(observation.ReasonCode),
		ObservedAt:        observation.ObservedAt,
	}); err != nil {
		return fmt.Errorf("persist target observation %s: %w", observation.TargetID, err)
	}
	return nil
}

func mapTargetSet(set targetdomain.Set) targetSet {
	mapped := targetSet{ReleaseID: set.ReleaseID, Targets: make([]targetSpec, 0, len(set.Targets))}
	for _, spec := range set.Targets {
		mapped.Targets = append(mapped.Targets, targetSpec{
			ID:                spec.ID,
			TargetRef:         spec.TargetRef,
			SourcePath:        spec.SourcePath,
			MediaKind:         spec.MediaKind,
			TargetPath:        spec.TargetPath,
			ExpectedSizeBytes: spec.ExpectedSizeBytes,
			Intent:            string(spec.Intent),
			CollisionPolicy:   string(spec.CollisionPolicy),
			RenderSnapshot:    spec.RenderSnapshot,
			ConfigSnapshot:    spec.ConfigSnapshot,
			SpecDigest:        spec.SpecDigest,
		})
	}
	return mapped
}

func mapObservation(observation targetdomain.Observation) observationRow {
	return observationRow{
		TargetID:          observation.TargetID,
		State:             string(observation.State),
		ObservedSizeBytes: observation.ObservedSizeBytes,
		ReasonCode:        observation.ReasonCode,
		ObservedAt:        observation.ObservedAt,
	}
}

func mapObservations(observations []targetdomain.Observation) []observationRow {
	mapped := make([]observationRow, 0, len(observations))
	for _, observation := range observations {
		mapped = append(mapped, mapObservation(observation))
	}
	return mapped
}

func transaction(scope txscope.Tx) (*sql.Tx, error) {
	tx := scope.SQLTx()
	if tx == nil {
		return nil, errors.New("target store: transaction is nil")
	}
	return tx, nil
}

func nullableInt64(value *int64) sql.NullInt64 {
	if value == nil {
		return sql.NullInt64{}
	}
	return sql.NullInt64{Int64: *value, Valid: true}
}

func nullableString(value string) sql.NullString {
	return sql.NullString{String: value, Valid: value != ""}
}

func normalizeObject(value json.RawMessage) json.RawMessage {
	if len(value) == 0 || strings.TrimSpace(string(value)) == "null" {
		return json.RawMessage(`{}`)
	}
	var object map[string]any
	if json.Unmarshal(value, &object) != nil || object == nil {
		return json.RawMessage(`{}`)
	}
	result, _ := json.Marshal(object)
	return result
}

var _ targetdomain.Repository = (*Repository)(nil)
