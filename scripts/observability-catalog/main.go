package main

import (
	"fmt"
	"os"
	"sort"

	observabilityport "bansoko/internal/observability/port"
)

func main() {
	routines := make(map[string]struct{})
	for _, identity := range observabilityport.RoutineIdentities() {
		routines[string(identity.Kind)] = struct{}{}
	}

	if _, err := fmt.Fprintln(os.Stdout, "// Code generated by scripts/ci/generate-observability-catalog.sh; DO NOT EDIT."); err != nil {
		panic(err)
	}
	writeConditions(observabilityport.ConditionCatalog())
	writeCatalog("ROUTINE_KINDS", sortedKeys(routines))

	kinds := make([]string, 0)
	for _, kind := range observabilityport.ActivityKinds() {
		kinds = append(kinds, string(kind))
	}
	codes := make([]string, 0)
	for _, spec := range observabilityport.MessageSpecs() {
		codes = append(codes, string(spec.Code))
	}
	writeCatalog("ACTIVITY_KINDS", kinds)
	writeCatalog("MESSAGE_CODES", codes)
	writeMessageSpecs(observabilityport.MessageSpecs())
}

// writeMessageSpecs publishes the business journal message catalog: per
// code, its kind and the params it interpolates, in registration order.
func writeMessageSpecs(specs []observabilityport.MessageSpec) {
	if _, err := fmt.Fprintf(os.Stdout, "\nexport const MESSAGE_PARAM_MAX_LENGTH = %d;\n", observabilityport.MaxMessageParamBytes); err != nil {
		panic(err)
	}
	if _, err := fmt.Fprintln(os.Stdout, "\nexport const MESSAGE_SPECS = {"); err != nil {
		panic(err)
	}
	for _, spec := range specs {
		params := ""
		for i, param := range spec.Params {
			if i > 0 {
				params += ", "
			}
			params += fmt.Sprintf("{ name: %q, type: %q, required: %t }", param.Name, string(param.Type), param.Required)
		}
		if _, err := fmt.Fprintf(os.Stdout, "  %q: { kind: %q, params: [%s] },\n", string(spec.Code), string(spec.Kind), params); err != nil {
			panic(err)
		}
	}
	if _, err := fmt.Fprintln(os.Stdout, "} as const;"); err != nil {
		panic(err)
	}
}

func sortedKeys(values map[string]struct{}) []string {
	keys := make([]string, 0, len(values))
	for value := range values {
		keys = append(keys, value)
	}
	sort.Strings(keys)
	return keys
}

func writeCatalog(name string, values []string) {
	if _, err := fmt.Fprintf(os.Stdout, "\nexport const %s = [\n", name); err != nil {
		panic(err)
	}
	for _, value := range values {
		if _, err := fmt.Fprintf(os.Stdout, "  %q,\n", value); err != nil {
			panic(err)
		}
	}
	if _, err := fmt.Fprintln(os.Stdout, "] as const;"); err != nil {
		panic(err)
	}
}

// writeConditions publishes the user-facing diagnostic condition catalog:
// per kind and variant, its retry mode and the settings target it points to.
// Internal conditions are not listed; they never reach the owner as episodes.
func writeConditions(specs []observabilityport.ConditionSpec) {
	if _, err := fmt.Fprintln(os.Stdout, "\nexport const DIAGNOSTIC_CONDITIONS = ["); err != nil {
		panic(err)
	}
	for _, spec := range specs {
		if spec.Audience != observabilityport.AudienceUser {
			continue
		}
		if _, err := fmt.Fprintf(os.Stdout, "  { kind: %q, variant: %q, retry: %q, settings: %q },\n",
			string(spec.Condition.Kind), string(spec.Condition.Variant), string(spec.Retry), string(spec.Settings)); err != nil {
			panic(err)
		}
	}
	if _, err := fmt.Fprintln(os.Stdout, "] as const;"); err != nil {
		panic(err)
	}
}
