package main

import (
	"fmt"
	"os"
	"sort"

	observabilityport "bansoko/internal/observability/port"
)

func main() {
	components := make([]string, 0)
	for _, component := range observabilityport.DiagnosticComponents() {
		components = append(components, string(component))
	}
	routines := make(map[string]struct{})
	for _, identity := range observabilityport.RoutineIdentities() {
		routines[string(identity.Kind)] = struct{}{}
	}

	if _, err := fmt.Fprintln(os.Stdout, "// Code generated by scripts/ci/generate-observability-catalog.sh; DO NOT EDIT."); err != nil {
		panic(err)
	}
	writeCatalog("DIAGNOSTIC_COMPONENTS", components)
	writeCatalog("ROUTINE_KINDS", sortedKeys(routines))
}

func sortedKeys(values map[string]struct{}) []string {
	keys := make([]string, 0, len(values))
	for value := range values {
		keys = append(keys, value)
	}
	sort.Strings(keys)
	return keys
}

func writeCatalog(name string, values []string) {
	if _, err := fmt.Fprintf(os.Stdout, "\nexport const %s = [\n", name); err != nil {
		panic(err)
	}
	for _, value := range values {
		if _, err := fmt.Fprintf(os.Stdout, "  %q,\n", value); err != nil {
			panic(err)
		}
	}
	if _, err := fmt.Fprintln(os.Stdout, "] as const;"); err != nil {
		panic(err)
	}
}
