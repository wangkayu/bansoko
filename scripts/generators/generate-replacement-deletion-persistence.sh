#!/usr/bin/env bash
# Generate and verify the bounded replacement-deletion owner sqlc persistence slice.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
expected_version="v1.31.1"
config="$root/internal/filemaintenance/adapter/persistence/sqlc.yaml"
generated_dir="$root/internal/filemaintenance/adapter/persistence/generated"
mode="generate"
if [[ "$#" == 1 && "$1" == "--check" ]]; then mode="check"; elif [[ "$#" != 0 ]]; then exit 2; fi
sqlc_bin="${SQLC_BIN:-$(command -v sqlc || true)}"
if [[ -z "$sqlc_bin" ]]; then
  gobin="$(go env GOBIN 2>/dev/null || true)"; gopath="$(go env GOPATH 2>/dev/null || true)"
  for candidate in "${gobin:+$gobin/sqlc}" "${gopath%%:*}/bin/sqlc"; do
    if [[ -n "$candidate" && -x "$candidate" ]]; then sqlc_bin="$candidate"; break; fi
  done
fi
[[ -n "$sqlc_bin" ]] || { echo "sqlc not found" >&2; exit 2; }
actual_version="$($sqlc_bin version 2>/dev/null || true)"
[[ "$actual_version" == "$expected_version" ]] || { echo "sqlc version mismatch: $actual_version" >&2; exit 2; }
cd "$root"
if [[ "$mode" == "generate" ]]; then "$sqlc_bin" generate --file "$config" --no-remote; fi
"$sqlc_bin" diff --no-remote -f "$config"
shopt -s nullglob; generated_files=("$generated_dir"/*.go); shopt -u nullglob
[[ "${#generated_files[@]}" -gt 0 ]] || { echo "no generated files" >&2; exit 2; }
for file in "${generated_files[@]}"; do
  grep -Fq '// Code generated by sqlc. DO NOT EDIT.' "$file" || exit 2
  grep -Fq "//   sqlc $expected_version" "$file" || exit 2
done
echo "Replacement deletion owner sqlc ${mode} passed with $actual_version"
