#!/usr/bin/env bash
# Generate and verify the bangumi-data snapshot sqlc persistence slice.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
expected_version="v1.31.1"
config="$root/internal/metadata/adapter/persistence/sqlc.yaml"
generated_dir="$root/internal/metadata/adapter/persistence/generated"
mode="generate"
if [[ "${1:-}" == "--check" ]]; then
  mode="check"
elif [[ "$#" -ne 0 ]]; then
  printf 'Usage: %s [--check]\n' "${0##*/}" >&2
  exit 2
fi
sqlc_bin="${SQLC_BIN:-$(command -v sqlc || true)}"
if [[ -z "$sqlc_bin" ]]; then
  sqlc_bin="$(go env GOPATH)/bin/sqlc"
fi
actual_version="$($sqlc_bin version 2>/dev/null || true)"
if [[ "$actual_version" != "$expected_version" ]]; then
  echo "sqlc version mismatch (expected $expected_version, found ${actual_version:-unknown})" >&2
  exit 2
fi
cd "$root"
if [[ "$mode" == "generate" ]]; then
  "$sqlc_bin" generate --file "$config" --no-remote
fi
"$sqlc_bin" diff --no-remote -f "$config"
for generated_file in "$generated_dir"/*.go; do
  grep -Fq '// Code generated by sqlc. DO NOT EDIT.' "$generated_file"
  grep -Fq "//   sqlc $expected_version" "$generated_file"
done
echo "Metadata persistence sqlc ${mode} passed with $actual_version"
