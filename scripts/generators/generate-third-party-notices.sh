#!/usr/bin/env bash
# Writes the third-party notice list to the path given as $1, from the Go
# build graph and the frontend production dependencies. Requires go and
# python3, plus the frontend's dependency licenses as either an installed
# node_modules (the default: cd frontend && CI=true pnpm install
# --frozen-lockfile --offline) or a `pnpm licenses list --prod --json` file
# passed as $2 — the image build collects that file in its frontend stage
# because the stage that can run `go list` has no Node.
set -euo pipefail
out="${1:?usage: generate-third-party-notices.sh <output.md> [frontend-licenses.json]}"
out="$(cd "$(dirname "$out")" && pwd)/$(basename "$out")"
fe_licenses="${2:-}"
if [ -n "$fe_licenses" ]; then
  fe_licenses="$(cd "$(dirname "$fe_licenses")" && pwd)/$(basename "$fe_licenses")"
fi
root="$(cd "$(dirname "$0")/../.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cd "$root"
go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/... | sort -u >"$tmp/go.txt"
if [ -n "$fe_licenses" ]; then
  cp "$fe_licenses" "$tmp/fe.json"
else
  (cd frontend && pnpm licenses list --prod --json) >"$tmp/fe.json"
fi
python3 -I - "$tmp/go.txt" "$tmp/fe.json" "$out" <<'PY'
import json, os, re, sys
go_file, fe_file, out = sys.argv[1:4]

def detect(text):
    t = text.lower()
    if "apache license" in t and "version 2.0" in t:
        return "Apache-2.0"
    if "permission is hereby granted, free of charge" in t:
        return "MIT"
    if "mozilla public license" in t:
        return "MPL-2.0"
    if "redistribution and use in source and binary forms" in t:
        return "BSD-3-Clause" if re.search(r"neither the name|endorse or promote", t) else "BSD-2-Clause"
    if "permission to use, copy, modify, and/or distribute" in t:
        return "ISC"
    return "UNKNOWN"

rows = []
for line in open(go_file):
    path, ver, d = line.rstrip("\n").split(" ", 2)
    lic, cr = "UNKNOWN", ""
    for n in sorted(os.listdir(d)):
        if re.match(r"(?i)(licen[sc]e|copying)", n):
            txt = open(os.path.join(d, n), errors="replace").read()
            lic = detect(txt)
            m = [l.strip() for l in txt.splitlines() if re.match(r"\s*copyright", l, re.I)]
            cr = m[0] if m else ""
            if lic == "Apache-2.0":
                cr = "see the module's LICENSE/NOTICE"
            break
    rows.append((path, ver, lic, cr))

fe = json.load(open(fe_file))
frows = []
for lic, pkgs in fe.items():
    for p in pkgs:
        for v in p["versions"]:
            frows.append((p["name"], v, lic, p.get("author") or ""))
frows.sort()

def esc(s):
    return s.replace("|", "\\|")

with open(out, "w") as f:
    f.write("# Third-party notices\n\n")
    f.write("Generated by `scripts/generators/generate-third-party-notices.sh`; do not edit by hand.\n\n")
    f.write("bansoko itself is GPL-3.0-only (see `LICENSE`). The components below are shipped in the binaries or the web frontend and keep their own licenses; the full license text of each ships with its package or module.\n\n")
    f.write("## Go modules\n\n| Module | Version | License | Copyright |\n|---|---|---|---|\n")
    for r in rows:
        f.write("| " + " | ".join(esc(x) for x in r) + " |\n")
    f.write("\n## Frontend production dependencies\n\n| Package | Version | License | Author |\n|---|---|---|---|\n")
    for r in frows:
        f.write("| " + " | ".join(esc(x) for x in r) + " |\n")
unknown = [r[0] for r in rows + frows if r[2] in ("UNKNOWN", "")]
print("go:", len(rows), "frontend:", len(frows), file=sys.stderr)
if unknown:
    print("no identifiable licence for: " + ", ".join(unknown), file=sys.stderr)
    sys.exit(1)
PY
