// Command fact-copy prints the zh-CN and en UI copy of the template fact
// registry (internal/templatefacts): one label and description per
// catalogued fact, keyed by its path, so the variable catalogs read
// t(fact.label_key) / t(fact.description_key).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"bansoko/internal/templatefacts"
)

type node struct {
	children map[string]*node
	label    *templatefacts.Text
	desc     *templatefacts.Text
}

func main() {
	root := &node{children: map[string]*node{}}
	for _, fact := range templatefacts.All() {
		if fact.Hidden {
			continue
		}
		current := root
		for _, segment := range strings.Split(fact.Path, ".") {
			next, ok := current.children[segment]
			if !ok {
				next = &node{children: map[string]*node{}}
				current.children[segment] = next
			}
			current = next
		}
		label, desc := fact.Label, fact.Description
		current.label, current.desc = &label, &desc
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by scripts/ci/generate-fact-copy.sh; DO NOT EDIT.\n")
	out.WriteString("// Labels and descriptions of the template fact registry (internal/templatefacts).\n\n")
	out.WriteString("import type { CopyShape } from \"./types\";\n\n")
	out.WriteString("export const factsCopy = ")
	write(&out, root, 0, func(t templatefacts.Text) string { return t.ZH })
	out.WriteString(" as const;\n\nexport const enFactsCopy = ")
	write(&out, root, 0, func(t templatefacts.Text) string { return t.EN })
	out.WriteString(" as const satisfies CopyShape<typeof factsCopy>;\n")
	if _, err := os.Stdout.Write(out.Bytes()); err != nil {
		panic(err)
	}
}

func quote(value string) string {
	var buf bytes.Buffer
	encoder := json.NewEncoder(&buf)
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		panic(err)
	}
	return strings.TrimSuffix(buf.String(), "\n")
}

func write(out *bytes.Buffer, n *node, depth int, pick func(templatefacts.Text) string) {
	indent := strings.Repeat("  ", depth+1)
	out.WriteString("{\n")
	if n.label != nil {
		if len(n.children) > 0 {
			panic(fmt.Sprintf("fact path is a prefix of another fact path at depth %d", depth))
		}
		fmt.Fprintf(out, "%slabel: %s,\n%sdescription: %s,\n", indent, quote(pick(*n.label)), indent, quote(pick(*n.desc)))
	}
	keys := make([]string, 0, len(n.children))
	for key := range n.children {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		fmt.Fprintf(out, "%s%s: ", indent, key)
		write(out, n.children[key], depth+1, pick)
		out.WriteString(",\n")
	}
	out.WriteString(strings.Repeat("  ", depth) + "}")
}
